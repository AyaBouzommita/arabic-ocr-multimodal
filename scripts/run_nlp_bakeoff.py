import sys
import json
import time
from pathlib import Path

# Add project root to path
sys.path.append(str(Path(__file__).resolve().parent.parent))

from arabic_ocr_platform.pipeline.pipeline import OCRPipeline

def format_arabic(text):
    """Helper to format Arabic text for correct RTL display in Windows terminals."""
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
        # We reshape the text to connect letters, and use get_display for RTL rendering
        return get_display(arabic_reshaper.reshape(text))
    except ImportError:
        # Fallback to original text if libraries are not installed
        return text

def run_bakeoff_report():
    print("="*60)
    print(" ARA-GPT2 / MARBERT CANDIDATE REPORT (NLP CORRECTION 3/3)")
    print("="*60)
    
    print("\n[1] Initializing Pipeline (Vision: YOLOv8, OCR: PaddleOCR, NLP: MARBERT)...")
    start_init = time.time()
    
    try:
        pipeline = OCRPipeline(vision_engine="yolov8", ocr_engine="paddleocr")
    except Exception as e:
        print(f"Warning during initialization (often due to missing models in local environment): {e}")
        # Proceeding anyway as this is a demonstration
        pipeline = OCRPipeline()
        
    print(f"Pipeline initialized in {time.time() - start_init:.2f}s")
    
    print("\n[2] Running Inference on Test Document...")
    start_inf = time.time()
    # In a real scenario, this would loop over a dataset. We use the mocked internal OCR data for the report.
    output = pipeline.process(image_path="test_doc.jpg", document_id="doc-001")
    latency = (time.time() - start_inf) * 1000  # ms
    
    print(f"\n[3] Candidate Report Results:")
    print("-" * 40)
    
    # Extract original text and corrected text
    # Original OCR mock was: "وثيقة صادرة عن وزارة الـ صحة"
    original_text = "وثيقة صادرة عن وزارة الـ صحة"
    final_text = output['ocr']['raw_text']
    
    print(f"Original OCR Text : {format_arabic(original_text)}")
    print(f"Corrected Text    : {format_arabic(final_text)}")
    print(f"End-to-End Latency: {latency:.2f} ms")
    
    print("\n[4] Correction Details:")
    for cand in output.get('correction_candidates', []):
        word = cand['original_word']
        print(f"  -> Original word with low confidence: '{format_arabic(word)}'")
        print("  -> Candidates generated by MARBERT:")
        for i, c in enumerate(cand['candidates']):
            print(f"       {i+1}. {format_arabic(c['text'])} (Score: {c['lm_score']:.4f})")
            
    print("\n[5] Full Fusion Output JSON:")
    # We do not format the JSON dump so that the underlying data remains raw and correct, 
    # but we could if we wanted the JSON to also render nicely in the terminal.
    # For now, it's best to leave the raw JSON as is.
    print(json.dumps(output, indent=2, ensure_ascii=False))
    print("="*60)

if __name__ == "__main__":
    run_bakeoff_report()
